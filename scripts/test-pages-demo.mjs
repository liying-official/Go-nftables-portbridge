import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
let clock=0,networkCalls=0;
const context=vm.createContext({window:{PB_I18N:{t:key=>key}},Response,Headers,TextEncoder,performance:{now:()=>clock},
  fetch:()=>{networkCalls++;throw Error('Demo must never use fetch');}});
vm.runInContext(fs.readFileSync(path.join(root,'docs/assets/demo-backend.js'),'utf8'),context);
const demo=context.window.PB_DEMO;
const call=async(url,method='GET',body,token='PortBridge',csrf='public-demo-csrf-not-a-security-token')=>{
  const response=await demo.request(url,{method,headers:{Authorization:'Bearer '+token,'X-PortBridge-CSRF':csrf},...(body===undefined?{}:{body:JSON.stringify(body)})});
  return {status:response.status,data:response.status===204?null:await response.json()};
};
assert.equal((await call('/api/bootstrap','GET',undefined,'wrong')).status,401);
assert.equal((await call('/api/bootstrap','GET',undefined,'portbridge')).status,401);
assert.equal((await call('/api/bootstrap')).data.csrf,'public-demo-csrf-not-a-security-token');
const config=(await call('/api/config')).data;
assert.equal(config.rules.length,4);
assert.deepEqual(Object.keys(config.web).sort(),['allow_insecure_http','auto_lan_acl','dns_servers','listen_ipv4','listen_ipv6','port','strict_ip_allowlist','tls_cert_file','tls_key_file','tls_min_version','whitelist'].sort());
const before=(await call('/api/status')).data;
assert.deepEqual(before.rules.map(row=>row.data_plane),['nftables','go-proxy','hybrid','disabled']);
clock=2000;
const after=(await call('/api/status')).data;
assert(after.rules[0].traffic.nft.bytes_up>before.rules[0].traffic.nft.bytes_up);
assert.equal(after.rules[3].traffic.go.bytes_up_per_second,0);
const rule={...config.rules[0],name:'<img src=x onerror=alert(1)>',data_plane:'go',protocol:'both'};
assert.equal((await call('/api/rules','POST',rule,'PortBridge','bad')).status,403);
assert.equal((await call('/api/rules','POST',{...rule,listen_port:0})).status,400);
assert.equal((await call('/api/rules','POST',{...rule,listen_port_end:8444})).status,400);
assert.equal((await call('/api/rules','POST',null)).status,400);
const created=await call('/api/rules','POST',rule);
assert.equal(created.status,201);assert(created.data.id.startsWith('demo-created-'));
const updated=await call('/api/rules/'+created.data.id,'PUT',{...created.data,enabled:false,id:'ignored'});
assert.equal(updated.status,200);assert.equal(updated.data.id,created.data.id);
assert.equal((await call('/api/rules/'+created.data.id,'DELETE')).status,204);
assert.equal((await call('/api/rules/'+created.data.id,'DELETE')).status,404);
assert.equal((await call('/api/settings','PUT',{...config.web,port:0})).status,400);
assert.equal((await call('/api/settings','PUT',{...config.web,port:9443})).status,200);
assert.equal((await call('/api/config')).data.web.port,9443);
assert.equal((await call('/api/token/rotate','POST')).data.token,'PortBridge');
assert.equal((await call('https://untrusted.example/api/config')).status,404);
assert.equal((await call('/metrics')).status,404);
demo.reset();assert.equal((await call('/api/config')).data.web.port,9080);
assert.equal((await call('/api/config')).data.rules.length,4);assert.equal(networkCalls,0);
const html=fs.readFileSync(path.join(root,'docs/index.html'),'utf8');
assert(html.includes("connect-src 'none'"));assert(html.includes("form-action 'none'"));
assert(!html.includes('="/static/'));
for(const match of html.matchAll(/(?:src|href)="(assets\/[^"#]+)(?:#[^"]*)?"/g))assert(fs.existsSync(path.join(root,'docs',match[1])),match[1]);
const app=fs.readFileSync(path.join(root,'docs/assets/ui/app.js'),'utf8');
assert(app.includes('window.PB_DEMO.request'));assert(!/\bfetch\s*\(/.test(app));assert(!app.includes("'portbridge_token'"));
const i18n=fs.readFileSync(path.join(root,'docs/assets/ui/i18n.js'),'utf8');
assert(i18n.includes('portbridge_demo_language'));assert(!i18n.includes('portbridge_language'));
console.log('Pages demo PASS: local CRUD/settings, public password, reset, counters, assets, no API network fallback.');
